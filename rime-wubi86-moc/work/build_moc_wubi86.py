def load_xdhycyc_freq():
    """现代汉语常用词表 频序号 map {词: 频序号}（频序号越小越常用）。多音字取最小频序号（最常用读音）。"""
    freq = {}
    with open(XDHYCYC, encoding="utf-8") as f:
        for line in f:
            p = line.rstrip("\n").split("\t")
            if len(p) >= 3 and p[0] != "词语":
                try: fo = int(p[-1])
                except ValueError: continue
                if p[0] not in freq or fo < freq[p[0]]:
                    freq[p[0]] = fo
    return freq


# 知乎/维基频 log10 映射参数（经验值，覆盖范围约 1 ~ 3.2×10⁷）
_LOG_FREQ_MAX = 7.5          # log10(维基频最大值) 经验上限
_ZHIHU_WEIGHT_MIN = 200      # 知乎/维基频校准保底 weight
_ZHIHU_WEIGHT_MAX = 30000    # 知乎/维基频校准上限 weight
# 两源加权融合：知乎（问答社区，接近打字场景）权重高于维基（百科，偏向阅读）
_ZHIHU_RATIO = 0.7
_WIKI_RATIO = 0.3


def load_zhihu_wiki_freq():
    """分别加载知乎频和维基频，返回 (zhihu, wiki) 两个 {词: 频数}。
    不再取 max——两源语料性质不同（知乎=讨论/打字，维基=百科/阅读），
    交给 calibrate_weight 分别 log 映射后加权融合，避免维基频让专有名词畸高。"""
    zhihu, wiki = {}, {}
    for path, target in ((ZHIHU_FREQ, zhihu), (WIKI_FREQ, wiki)):
        if not path.exists():
            print(f"[calibrate] 警告：缺 {path.name}，跳过", file=sys.stderr)
            continue
        with open(path, encoding="utf-8") as f:
            for line in f:
                p = line.rstrip("\n").split("\t")
                if len(p) < 2:
                    continue
                text, count_s = p[0], p[1]
                try:
                    count = int(count_s)
                except ValueError:
                    continue
                if text not in target or count > target[text]:
                    target[text] = count
    return zhihu, wiki


def _zhihu_weight(count):
    """将知乎/维基频原始频数映射到 [_ZHIHU_WEIGHT_MIN, _ZHIHU_WEIGHT_MAX]。"""
    if count <= 0:
        return _ZHIHU_WEIGHT_MIN
    log_f = math.log10(count)
    # 线性映射：log_f=0 → _ZHIHU_WEIGHT_MIN, log_f=_LOG_FREQ_MAX → _ZHIHU_WEIGHT_MAX
    w = _ZHIHU_WEIGHT_MIN + (log_f / _LOG_FREQ_MAX) * (_ZHIHU_WEIGHT_MAX - _ZHIHU_WEIGHT_MIN)
    return int(max(_ZHIHU_WEIGHT_MIN, min(_ZHIHU_WEIGHT_MAX, w)))


def load_jidian_raw_weight():
    """加载极点原表的原始 weight，返回 {(text, code): raw_weight}。
    用于在知乎/维基频校准后，按编码内极点经验做二次微调。"""
    weights = {}
    with open(JIDIAN_DICT, encoding="utf-8") as f:
        in_data = False
        for line in f:
            s = line.rstrip("\n")
            if not in_data:
                if s.strip() == "...":
                    in_data = True
                continue
            if not s.strip() or s.lstrip().startswith("#"):
                continue
            parts = s.split("\t")
            if len(parts) >= 3:
                text, code = parts[0], parts[1].lower()
                try:
                    w = int(parts[2])
                except ValueError:
                    w = 0
                key = (text, code)
                # 同一 text+code 取最大 weight（去重）
                if key not in weights or w > weights[key]:
                    weights[key] = w
    return weights


# RRF（Reciprocal Rank Fusion）排名融合参数
# 两个信号各自排名后按 1/(k+rank) 求和融合，消除桶化方案的盲区
_RRF_K = 60                  # RRF 平滑常数（信息检索经典值，IEEE 2009）
_RRF_JIDIAN_W = 2.0          # 极点信号权重（>1：极点为五笔打字场景专门标注，比通用语料更相关）
_RRF_BASE = 40000            # 非简码词组内最高 weight（低于二级简码 80000，按组内位置递减）
_JIDIAN_SIGNAL_MIN = 10      # 极点 raw weight 阈值：≤此值视为无信号（极点表 77171/89265 条是默认值 10，无区分度）

# 一级简码从极点原表动态提取（load_jidian_1char）。
# 不硬编码：极点原表 b 键 top1 是"了"而非官方字根表的"子"，实用场景"了"更常用。
# 25 个键中 24 个与官方表一致，仅 b 不同——尊重极点（成熟方案）与用户习惯。
_JIANMA_FALLBACK = {
    'a': '工', 'b': '了', 'c': '以', 'd': '在', 'e': '有', 'f': '地',
    'g': '一', 'h': '上', 'i': '不', 'j': '是', 'k': '中', 'l': '国',
    'm': '同', 'n': '民', 'o': '为', 'p': '这', 'q': '我', 'r': '的',
    's': '要', 't': '和', 'u': '产', 'v': '发', 'w': '人', 'x': '经',
    'y': '主',
}
_JIANMA_WEIGHT = 99999      # 一级简码固定最高 weight
_JIANMA2_WEIGHT = 80000     # 二级简码固定高 weight（低于一级，高于任何 RRF 映射）


def load_jidian_1char():
    """从极点原表提取一级简码（单字母编码）的最高 weight 候选。
    返回 {code: text}。极点原表缺某键时回落到 _JIANMA_FALLBACK。

    实测：25 个键中 24 个与官方五笔86字根表一致，仅 b 不同（极点"了" vs 官方"子"），
    "了"是超高频虚词，尊重极点的实际选择。"""
    best = {}
    with open(JIDIAN_DICT, encoding="utf-8") as f:
        in_data = False
        for line in f:
            s = line.rstrip("\n")
            if not in_data:
                if s.strip() == "...":
                    in_data = True
                continue
            if not s.strip() or s.lstrip().startswith("#"):
                continue
            parts = s.split("\t")
            if len(parts) >= 3 and len(parts[1]) == 1:
                text, code = parts[0], parts[1].lower()
                try:
                    w = int(parts[2])
                except ValueError:
                    w = 0
                if code not in best or w > best[code][1]:
                    best[code] = (text, w)
    extracted = {code: text for code, (text, _) in best.items()}
    # 极点缺某键时回落到 fallback（确保 25 个键齐全）
    for code, text in _JIANMA_FALLBACK.items():
        extracted.setdefault(code, text)
    return extracted


def load_jidian_2char():
    """从极点原表提取二级简码（双字母编码）的最高 weight 候选。
    返回 {code: text}。

    局限：极点原表双字母编码 94% weight=10，作者未刻意标注二级简码，
    提取结果正确性依赖极点表的成熟度（实测 88% 频数≥1000）。
    理想方案应替换为标准五笔86二级简码表，但当前无权威源。"""
    best = {}
    with open(JIDIAN_DICT, encoding="utf-8") as f:
        in_data = False
        for line in f:
            s = line.rstrip("\n")
            if not in_data:
                if s.strip() == "...":
                    in_data = True
                continue
            if not s.strip() or s.lstrip().startswith("#"):
                continue
            parts = s.split("\t")
            if len(parts) >= 3 and len(parts[1]) == 2:
                text, code = parts[0], parts[1].lower()
                try:
                    w = int(parts[2])
                except ValueError:
                    w = 0
                if code not in best or w > best[code][1]:
                    best[code] = (text, w)
    return {code: text for code, (text, _) in best.items()}


def calibrate_weight(rows, xdhycyc_freq, zhihu_freq, wiki_freq, jidian_raw, jidian_1char, jidian_2char):
    """RRF 双信号排名融合校准：
    1) 一/二级简码固定高 weight（肌肉记忆硬规则；均从极点原表动态提取）；
    2) 其余词按编码分组，组内对两个信号各自排名：
       - 频数信号（知乎/维基频加权融合，常用词表/保底为辅）
       - 极点信号（极点原表 raw weight；frost 词无此信号则该项缺省）
    3) score = 1/(_RRF_K+rank_freq) + _RRF_JIDIAN_W × 1/(_RRF_K+rank_jidian)；
    4) 组内按 (score, 极点 raw weight) 排序赋唯一递减 weight，极点做 tie-break。

    频数信号：知乎/维基分别 log 映射后按 _ZHIHU_RATIO/_WIKI_RATIO 加权，
    避免维基频让百科专有名词（如"拿破仑"）畸高压过日常词（如"优化"）。
    """
    from collections import defaultdict

    # 第一遍：算 base / jidian_w / 简码标记
    items = []
    for idx, (text, code, w, stem) in enumerate(rows):
        code_l = code.lower()
        is_jm1 = code_l in jidian_1char and text == jidian_1char[code_l]
        is_jm2 = code_l in jidian_2char and text == jidian_2char[code_l]
        zw = _zhihu_weight(zhihu_freq[text]) if text in zhihu_freq else None
        ww = _zhihu_weight(wiki_freq[text]) if text in wiki_freq else None
        if zw is not None and ww is not None:
            base = int(_ZHIHU_RATIO * zw + _WIKI_RATIO * ww)
        elif zw is not None:
            base = zw
        elif ww is not None:
            base = ww
        elif text in xdhycyc_freq:
            base = MAX_FREQ_ORDER - xdhycyc_freq[text]
        else:
            base = max(100, w)
        jw_raw = jidian_raw.get((text, code_l))
        # 极点默认值 w=10 无区分度（占 86%），视为无信号，避免"碰巧有条目"的词拿到 bonus
        jw = jw_raw if (jw_raw is not None and jw_raw > _JIDIAN_SIGNAL_MIN) else None
        items.append([idx, text, code, stem, base, jw, is_jm1, is_jm2])

    # 按编码分组，组内 RRF
    groups = defaultdict(list)
    for it in items:
        groups[it[2].lower()].append(it)
    for code_l, grp in groups.items():
        n = len(grp)
        # rank_freq：按 base 降序，0=最常用
        order_f = sorted(range(n), key=lambda i: -grp[i][4])
        rank_f = [0] * n
        for r, i in enumerate(order_f):
            rank_f[i] = r
        # rank_jidian：仅对有极点信号的词排名
        has_jw = [i for i in range(n) if grp[i][5] is not None]
        order_j = sorted(has_jw, key=lambda i: -grp[i][5])
        rank_j = {}
        for r, i in enumerate(order_j):
            rank_j[i] = r
        # RRF 融合分数
        for i in range(n):
            s = 1.0 / (_RRF_K + rank_f[i])
            if i in rank_j:
                s += _RRF_JIDIAN_W * 1.0 / (_RRF_K + rank_j[i])
            grp[i].append(s)
        # 组内按 (score 降序, 极点 raw weight 降序) 排序，赋唯一递减 weight
        # 极点 raw weight 作为 tie-break：RRF 平局时尊重极点经验
        order = sorted(range(n), key=lambda i: (-grp[i][8], -(grp[i][5] or 0)))
        for pos, i in enumerate(order):
            grp[i].append(pos)  # grp[i][9] = 组内位置

    # 赋最终 weight（保留原始行顺序）
    # 非简码词：weight = 40000 - 组内位置，保证同编码内递减且唯一，绝对值低于简码保护
    out = [None] * len(rows)
    for it in items:
        idx, text, code, stem, base, jw, is_jm1, is_jm2, score, pos = it
        if is_jm1:
            final_w = _JIANMA_WEIGHT
        elif is_jm2:
            final_w = _JIANMA2_WEIGHT
        else:
            final_w = _RRF_BASE - pos
        out[idx] = (text, code, final_w, stem)
    return out


def filter_wubi_rows(rows, drop_weights_below=None, exclude_texts=None, exclude_keys=None, whitelist=None):
    """五笔候选过滤：去 non-CJK、去繁体/异体、去生僻字(不在白名单)；可选权重阈值与去重。

    去重两种模式：
    - exclude_texts：按 text 全局去重（不管编码）
    - exclude_keys：按 (text, code.lower()) 去重，保留同 text 不同 code 的合法编码变体

    生僻字规则：单字不在 8105 白名单 -> 删；词组任一汉字不在 -> 整词删。
    非汉字字符（数字/字母）不触发白名单检查。
    """
    exclude_texts = exclude_texts or set()
    exclude_keys = exclude_keys or set()
    kept, n_ncjk, n_trad, n_rare, n_weight, n_dup = [], 0, 0, 0, 0, 0
    for text, code, w, stem in rows:
        if not has_cjk(text):
            n_ncjk += 1
            continue
        if has_traditional(text):
            n_trad += 1
            continue
        if whitelist is not None and any(c not in whitelist for c in text if has_cjk(c)):
            n_rare += 1
            continue
        if drop_weights_below is not None and w < drop_weights_below:
            n_weight += 1
            continue
        if text in exclude_texts or (text, code.lower()) in exclude_keys:
            n_dup += 1
            continue
        kept.append((text, code, w, stem))
    return kept, dict(non_cjk=n_ncjk, traditional=n_trad, rare=n_rare,
                      low_weight=n_weight, dup=n_dup)


