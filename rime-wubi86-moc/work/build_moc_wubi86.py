# ---------- 通用 rime dict 解析/写出 ----------
def parse_header_columns(path):
    """从 dict.yaml header 提取 columns；无则返回 None。"""
    cols, in_header, in_cols = [], False, False
    with open(path, encoding="utf-8") as f:
        for line in f:
            s = line.rstrip("\n")
            if s.strip() == "---":
                in_header = True
                continue
            if s.strip() == "...":
                break
            if not in_header:
                continue
            if s.startswith("columns:"):
                in_cols = True
                continue
            if in_cols:
                if s.lstrip().startswith("- "):
                    val = s.strip()[2:].strip()
                    if "#" in val:
                        val = val.split("#", 1)[0].strip()
                    cols.append(val)
                else:
                    in_cols = False
    return cols or None


def parse_dict(path):
    """返回 rows: list of (text, code, weight, stem)。weight 为 int。"""
    cols = parse_header_columns(path) or ["text", "code", "weight", "stem"]
    idx = {c: i for i, c in enumerate(cols)}
    rows, in_data = [], False
    with open(path, encoding="utf-8") as f:
        for line in f:
            s = line.rstrip("\n")
            if not in_data:
                if s.strip() == "...":
                    in_data = True
                continue
            if not s.strip() or s.lstrip().startswith("#"):
                continue
            parts = s.split("\t")
            def get(col, default=""):
                i = idx.get(col)
                return parts[i] if i is not None and i < len(parts) else default
            text = get("text")
            if not text:
                continue
            try:
                w = int(get("weight", "0"))
            except ValueError:
                w = 0
            rows.append((text, get("code"), w, get("stem")))
    return rows


def write_dict(path, name, rows, note):
    """写 moc 风格 dict.yaml：4列 text/code/weight/stem，sort: by_weight。"""
    path.parent.mkdir(parents=True, exist_ok=True)
    with open(path, "w", encoding="utf-8") as f:
        f.write("# Rime dictionary\n# encoding: utf-8\n")
        f.write(f"# Generated by work/build_moc_wubi86.py. Do not edit by hand.\n")
        f.write("---\n")
        f.write(f'name: {name}\nversion: "{VERSION}"\nsort: by_weight\n')
        f.write(f"note: '{note}'\n")
        f.write("columns:\n  - text\n  - code\n  - weight\n  - stem\n...\n")
        for text, code, w, stem in rows:
            f.write(f"{text}\t{code}\t{w}\t{stem}\n")


